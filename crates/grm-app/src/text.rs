mod tests {
    use super::*;

    #[test]
    fn every_word_has_both_languages_and_no_key_twice() {
        let mut seen = std::collections::HashSet::new();
        for (k, en, fr) in WORDS {
            assert!(seen.insert(*k), "{k} twice");
            assert!(!en.is_empty() && !fr.is_empty(), "{k}");
        }
    }
}
